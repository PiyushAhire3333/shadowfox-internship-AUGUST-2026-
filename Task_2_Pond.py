PI, radius = 3.14, 84

pond_area   = PI * radius ** 2       
total_water = pond_area * 1.4        

print(int(total_water))           


# the output will be 31104, which is the total amount of water in the pond, 
# calculated using the formula for the area of a circle (πr²) and multiplying 
# it by 1.4 to account for the depth of the water.